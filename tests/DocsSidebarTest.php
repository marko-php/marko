<?php

declare(strict_types=1);

/*
 * Tests the check behind `composer docs:lint` that every docs page has a
 * sidebar entry, against fixtures. The real sidebar and pages are checked by
 * `composer docs:lint` in the CI Lint job, never here: tests do not read
 * documentation.
 */

$fixtureRoot = __DIR__ . '/Fixtures/DocsSidebar';

/**
 * @return array{exitCode: int, output: string}
 */
function runDocsSidebarLint(string ...$arguments): array
{
    $command = array_merge([PHP_BINARY, dirname(__DIR__) . '/bin/docs-sidebar-lint.php'], $arguments);
    $process = proc_open($command, [1 => ['pipe', 'w'], 2 => ['redirect', 1]], $pipes);
    $output = (string) stream_get_contents($pipes[1]);
    fclose($pipes[1]);

    return ['exitCode' => proc_close($process), 'output' => $output];
}

it('fails and names every docs page that has no sidebar entry', function () use ($fixtureRoot): void {
    $result = runDocsSidebarLint(
        '--config=' . $fixtureRoot . '/unlisted/astro.config.mjs',
        '--pages=' . $fixtureRoot . '/unlisted/docs',
    );

    expect($result['exitCode'])->toBe(1)
        ->and($result['output'])
        ->toContain('guides/unlisted.md has no sidebar entry')
        ->toContain('concepts/also-unlisted.mdx has no sidebar entry')
        ->toContain('2 docs page(s)');
});

it(
    'treats index pages as their directory, autogenerated directories as listed, and skips the home page',
    function () use ($fixtureRoot): void {
        $result = runDocsSidebarLint(
            '--config=' . $fixtureRoot . '/unlisted/astro.config.mjs',
            '--pages=' . $fixtureRoot . '/unlisted/docs',
        );

        expect($result['output'])
            ->toContain('guides/unlisted.md has no sidebar entry')
            ->not->toContain('section/index.md')
            ->not->toContain('packages/demo/auto.md')
            ->not->toContain('guides/listed.md')
            ->not->toContain('index.mdx has');
    },
);

it('passes when every docs page has a sidebar entry', function () use ($fixtureRoot): void {
    $result = runDocsSidebarLint(
        '--config=' . $fixtureRoot . '/complete/astro.config.mjs',
        '--pages=' . $fixtureRoot . '/complete/docs',
    );

    expect($result['exitCode'])->toBe(0)
        ->and($result['output'])->toContain('every docs page has a sidebar entry');
});

it('fails loudly when the sidebar config does not exist', function () use ($fixtureRoot): void {
    $result = runDocsSidebarLint(
        '--config=' . $fixtureRoot . '/missing/astro.config.mjs',
        '--pages=' . $fixtureRoot . '/complete/docs',
    );

    expect($result['exitCode'])->toBe(1)
        ->and($result['output'])->toContain('sidebar config not found');
});

it('fails loudly when the sidebar config lists no entries', function (): void {
    $base = sys_get_temp_dir() . '/marko-docs-sidebar-empty-' . uniqid();
    mkdir($base . '/docs/guides', recursive: true);
    file_put_contents($base . '/astro.config.mjs', "export default { sidebar: [] };\n");
    file_put_contents($base . '/docs/guides/page.md', "---\ntitle: Page\n---\n");

    try {
        $result = runDocsSidebarLint('--config=' . $base . '/astro.config.mjs', '--pages=' . $base . '/docs');
    } finally {
        unlink($base . '/docs/guides/page.md');
        unlink($base . '/astro.config.mjs');
        rmdir($base . '/docs/guides');
        rmdir($base . '/docs');
        rmdir($base);
    }

    expect($result['exitCode'])->toBe(1)
        ->and($result['output'])->toContain('found no sidebar entries');
});

it('fails loudly when it finds no docs pages', function (): void {
    $base = sys_get_temp_dir() . '/marko-docs-sidebar-nopages-' . uniqid();
    mkdir($base . '/docs', recursive: true);
    file_put_contents($base . '/astro.config.mjs', "export default { sidebar: [{ slug: 'a' }] };\n");

    try {
        $result = runDocsSidebarLint('--config=' . $base . '/astro.config.mjs', '--pages=' . $base . '/docs');
    } finally {
        unlink($base . '/astro.config.mjs');
        rmdir($base . '/docs');
        rmdir($base);
    }

    expect($result['exitCode'])->toBe(1)
        ->and($result['output'])->toContain('found no docs pages');
});
